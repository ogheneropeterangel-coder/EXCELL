    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='fee_records' AND column_name='balance') THEN
        ALTER TABLE fee_records ADD COLUMN balance NUMERIC GENERATED ALWAYS AS (total_amount - amount_paid) STORED;
