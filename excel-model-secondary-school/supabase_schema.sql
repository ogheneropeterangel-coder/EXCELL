-- TRIGGER FOR PROFILE CREATION
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger 
LANGUAGE plpgsql 
SECURITY DEFINER 
SET search_path = public
AS $$
DECLARE
  default_role user_role := 'teacher';
  meta_role text;
BEGIN
  meta_role := new.raw_user_meta_data->>'role';
  
  INSERT INTO public.profiles (id, name, username, email, role)
  VALUES (
    new.id, 
    COALESCE(new.raw_user_meta_data->>'name', 'User'), 
    NULLIF(TRIM(new.raw_user_meta_data->>'username'), ''),
    new.email, 
    CASE 
      WHEN meta_role = 'admin' THEN 'admin'::user_role
      WHEN meta_role = 'teacher' THEN 'teacher'::user_role
      WHEN meta_role = 'student' THEN 'student'::user_role
      WHEN meta_role = 'cashier' THEN 'cashier'::user_role
      ELSE default_role
    END
  )
  ON CONFLICT (id) DO UPDATE SET
    name = EXCLUDED.name,
    username = EXCLUDED.username,
    email = EXCLUDED.email,
    role = EXCLUDED.role;
    
  RETURN new;
EXCEPTION
  WHEN others THEN
    -- In a trigger, we should ideally not fail the main transaction
    -- But "Database error saving new user" often means the trigger failed and wasn't caught.
    -- We'll log it to the postgres log.
    RAISE WARNING 'Error in handle_new_user trigger for user %: %', new.id, SQLERRM;
    RETURN new;
END;
$$;

-- Drop trigger if exists before creating to avoid errors
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- Function to sync role from profile to auth.users metadata
CREATE OR REPLACE FUNCTION public.sync_user_role_to_metadata()
RETURNS trigger AS $$
BEGIN
  UPDATE auth.users
  SET raw_user_meta_data = 
    COALESCE(raw_user_meta_data, '{}'::jsonb) || 
    jsonb_build_object('role', NEW.role::text)
  WHERE id = NEW.id;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_profile_role_sync ON profiles;
CREATE TRIGGER on_profile_role_sync
  AFTER INSERT OR UPDATE OF role ON profiles
  FOR EACH ROW EXECUTE PROCEDURE public.sync_user_role_to_metadata();

-- 11. HELPER FUNCTIONS FOR RLS (Prevents recursion)
-- We use SECURITY DEFINER so they run as the owner (postgres) bypassing RLS
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean 
LANGUAGE plpgsql 
SECURITY DEFINER 
SET search_path = public, auth
AS $$
BEGIN
  -- 1. Check JWT metadata first (fastest)
  IF (auth.jwt() -> 'user_metadata' ->> 'role') = 'admin' THEN
    RETURN TRUE;
  END IF;

  -- 2. Fallback to profiles table
  RETURN EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = auth.uid() AND role = 'admin'::public.user_role
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.is_teacher()
RETURNS boolean 
LANGUAGE plpgsql 
SECURITY DEFINER 
SET search_path = public, auth
AS $$
BEGIN
  -- 1. Check JWT metadata
  IF (auth.jwt() -> 'user_metadata' ->> 'role') = 'teacher' THEN
    RETURN TRUE;
  END IF;

  -- 2. Fallback to profiles table
  RETURN EXISTS (
