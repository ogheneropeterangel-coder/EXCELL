-- Safely add missing columns or change types
DO $$ BEGIN
    -- Add last_updated_by if missing
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='fee_records' AND column_name='last_updated_by') THEN
        ALTER TABLE fee_records ADD COLUMN last_updated_by UUID REFERENCES profiles(id) ON DELETE SET NULL;
    END IF;

    -- Add updated_at if missing
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='fee_records' AND column_name='updated_at') THEN
        ALTER TABLE fee_records ADD COLUMN updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW();
    END IF;

    -- Convert status to enum if it's still text
    IF EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_name = 'fee_records' AND column_name = 'status' AND data_type = 'text'
    ) THEN
        ALTER TABLE fee_records ALTER COLUMN status DROP DEFAULT;
        ALTER TABLE fee_records ALTER COLUMN status TYPE fee_payment_status USING (
            CASE 
                WHEN status = 'Paid' THEN 'Paid'::fee_payment_status
                WHEN status = 'Partial' THEN 'Partial'::fee_payment_status
                ELSE 'Not Paid'::fee_payment_status
            END
        );
        ALTER TABLE fee_records ALTER COLUMN status SET DEFAULT 'Not Paid'::fee_payment_status;
    END IF;
END $$;

