-- AUTOMATIC STUDENT USER CREATION & SYNC
-- This function creates/updates an auth user and profile for each student
CREATE OR REPLACE FUNCTION public.handle_student_changes()
RETURNS trigger AS $$
DECLARE
  new_user_id UUID;
BEGIN
  -- 1. Handle INSERT
  IF (TG_OP = 'INSERT') THEN
    -- Check if the user already exists to avoid errors
    SELECT id INTO new_user_id FROM auth.users WHERE email = (NEW.admission_number || '@school.com');
    
    IF new_user_id IS NULL THEN
      INSERT INTO auth.users (
        instance_id,
        id,
        aud,
        role,
        email,
        encrypted_password,
        email_confirmed_at,
        recovery_sent_at,
        last_sign_in_at,
        raw_app_meta_data,
        raw_user_meta_data,
        created_at,
        updated_at,
        confirmation_token,
        email_change,
        email_change_token_new,
        recovery_token
      )
      VALUES (
        '00000000-0000-0000-0000-000000000000',
        gen_random_uuid(),
        'authenticated',
        'authenticated',
        NEW.admission_number || '@school.com',
        crypt(NEW.admission_number, gen_salt('bf')), -- Admission number as password (always >= 6 chars)
        now(),
        now(),
        now(),
        '{"provider":"email","providers":["email"]}',
        jsonb_build_object('name', NEW.first_name || ' ' || NEW.last_name, 'role', 'student', 'username', NEW.admission_number),
        now(),
        now(),
        '',
        '',
        '',
        ''
      )
      RETURNING id INTO new_user_id;
    END IF;

    -- Create/Update Profile
    INSERT INTO public.profiles (id, name, username, email, role)
    VALUES (
      new_user_id,
      NEW.first_name || ' ' || NEW.last_name,
      NEW.admission_number,
      NEW.admission_number || '@school.com',
      'student'
    )
    ON CONFLICT (id) DO UPDATE SET
      username = EXCLUDED.username,
      name = EXCLUDED.name,
      email = EXCLUDED.email,
      role = 'student';

  -- 2. Handle UPDATE
  ELSIF (TG_OP = 'UPDATE') THEN
    -- If surname or admission number changed, update auth and profile
    IF (NEW.last_name <> OLD.last_name OR NEW.admission_number <> OLD.admission_number OR NEW.first_name <> OLD.first_name) THEN
      -- Update auth user
      UPDATE auth.users 
      SET encrypted_password = crypt(NEW.admission_number, gen_salt('bf')),
          email = NEW.admission_number || '@school.com',
          raw_user_meta_data = raw_user_meta_data || jsonb_build_object('name', NEW.first_name || ' ' || NEW.last_name, 'username', NEW.admission_number),
          updated_at = now()
      WHERE email = OLD.admission_number || '@school.com';
      
      -- Update profile
      UPDATE public.profiles
      SET name = NEW.first_name || ' ' || NEW.last_name,
          username = NEW.admission_number,
          email = NEW.admission_number || '@school.com'
      WHERE username = OLD.admission_number;
    END IF;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger for student changes
DROP TRIGGER IF EXISTS on_student_changes ON students;
CREATE TRIGGER on_student_changes
  AFTER INSERT OR UPDATE ON students
  FOR EACH ROW EXECUTE PROCEDURE public.handle_student_changes();

-- BULK SYNC FUNCTION FOR EXISTING STUDENTS
CREATE OR REPLACE FUNCTION public.sync_all_students()
RETURNS text AS $$
DECLARE
  student_record RECORD;
  sync_count INTEGER := 0;
  new_user_id UUID;
BEGIN
  FOR student_record IN SELECT * FROM public.students LOOP
    -- Check if user already exists
    SELECT id INTO new_user_id FROM auth.users WHERE email = (student_record.admission_number || '@school.com');
    
    IF new_user_id IS NULL THEN
      INSERT INTO auth.users (
        instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
        raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token
      )
      VALUES (
        '00000000-0000-0000-0000-000000000000', gen_random_uuid(), 'authenticated', 'authenticated',
        student_record.admission_number || '@school.com', crypt(student_record.admission_number, gen_salt('bf')),
        now(), '{"provider":"email","providers":["email"]}',
        jsonb_build_object('name', student_record.first_name || ' ' || student_record.last_name, 'role', 'student', 'username', student_record.admission_number),
        now(), now(), ''
      )
      RETURNING id INTO new_user_id;
      sync_count := sync_count + 1;
    END IF;

    -- Upsert profile
    INSERT INTO public.profiles (id, name, username, email, role)
    VALUES (
      new_user_id,
      student_record.first_name || ' ' || student_record.last_name,
      student_record.admission_number,
      student_record.admission_number || '@school.com',
      'student'
    )
    ON CONFLICT (id) DO UPDATE SET
      username = EXCLUDED.username,
      name = EXCLUDED.name,
      email = EXCLUDED.email,
      role = 'student';
  END LOOP;
  
  RETURN 'Synced ' || sync_count || ' students.';
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

